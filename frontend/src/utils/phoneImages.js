/**
 * Trả về ảnh chính xác theo Tên sản phẩm & Màu sắc
 * NGUYÊN TẮC VÀNG:
 * 1. Nếu có fallbackUrl hợp lệ từ database (bắt đầu bằng http và không phải link lỗi apple.com) -> Dùng làm nền tảng
 * 2. Nếu có màu cụ thể được định nghĩa trong từ điển -> Dùng ảnh màu đó
 * 3. Nếu không có màu riêng -> Trả về fallbackUrl gốc từ database
 */
export function getSmartColorImage(productName = "", colorName = "", fallbackUrl = null) {
  const pLower = (productName || "").toLowerCase();
  const cLower = (colorName || "").toLowerCase();

  // Kiểm tra xem fallbackUrl từ database có hợp lệ không
  const isFallbackValid =
    fallbackUrl &&
    typeof fallbackUrl === "string" &&
    fallbackUrl.startsWith("http") &&
    !fallbackUrl.includes("apple.com") && // Bỏ qua link CDN Apple bị 403
    !fallbackUrl.includes("-_5.png") &&   // Bỏ qua ảnh sơ đồ mạch
    !fallbackUrl.includes("placeholder");

  // Tìm trong từ điển ảnh theo độ khớp chính xác nhất (tên dài ưu tiên trước)
  const sortedKeys = Object.keys(VERIFIED_PHONE_IMAGES).sort((a, b) => b.length - a.length);

  for (const phoneKey of sortedKeys) {
    if (pLower.includes(phoneKey)) {
      const colorDict = VERIFIED_PHONE_IMAGES[phoneKey];
      // Nếu có tên màu cụ thể và từ điển có ảnh cho màu đó
      if (cLower) {
        for (const [cKey, imgUrl] of Object.entries(colorDict)) {
          if (cKey !== "_default" && cLower.includes(cKey)) {
            return imgUrl;
          }
        }
      }
      // Nếu không khớp màu riêng nhưng từ điển có ảnh mặc định cho model này
      if (isFallbackValid) {
        return fallbackUrl;
      }
      if (colorDict._default) {
        return colorDict._default;
      }
    }
  }

  // Nếu không khớp từ điển cụ thể, ưu tiên trả về fallbackUrl từ database
  if (isFallbackValid) {
    return fallbackUrl;
  }

  // Fallback an toàn theo hãng sản xuất
  if (pLower.includes("iphone") || pLower.includes("apple")) {
    return "https://cdn2.cellphones.com.vn/insecure/rs:fill:0:358/q:90/plain/https://cellphones.com.vn/media/catalog/product/i/p/iphone-16-pro-max.png";
  }
  if (pLower.includes("s24") || pLower.includes("galaxy")) {
    return "https://cdn2.cellphones.com.vn/insecure/rs:fill:358:358/q:90/plain/https://cellphones.com.vn/media/catalog/product/s/s/ss-s24-ultra-xam-222_3_1.png";
  }
  if (pLower.includes("xiaomi") || pLower.includes("redmi")) {
    return "https://cdn2.cellphones.com.vn/insecure/rs:fill:0:358/q:90/plain/https://cellphones.com.vn/media/catalog/product/x/i/xiaomi-14-ultra_1.png";
  }
  if (pLower.includes("oppo") || pLower.includes("find")) {
    return "https://cdn2.cellphones.com.vn/insecure/rs:fill:0:358/q:90/plain/https://cellphones.com.vn/media/catalog/product/f/i/find_n3_16gb_512gb.png";
  }

  return fallbackUrl || "https://cdn2.cellphones.com.vn/insecure/rs:fill:0:358/q:90/plain/https://cellphones.com.vn/media/catalog/product/i/p/iphone-16-pro-max.png";
}

/**
 * Tự động nhận diện Hãng sản xuất chính xác (KHÔNG BAO GIỜ bị nhầm sang Apple)
 */
export function detectSmartBrand(productName = "", brandObj = null) {
  if (brandObj && typeof brandObj === "object" && brandObj.name) {
    return brandObj.name;
  }
  if (typeof brandObj === "string" && brandObj.trim()) {
    return brandObj.trim();
  }

  const n = (productName || "").toLowerCase();
  if (n.includes("iphone") || n.includes("apple") || n.includes("ipad")) return "Apple";
  if (n.includes("samsung") || n.includes("galaxy") || n.includes("fold") || n.includes("flip")) return "Samsung";
  if (n.includes("redmi")) return "Xiaomi";
  if (n.includes("xiaomi") || n.includes("poco")) return "Xiaomi";
  if (n.includes("oppo") || n.includes("find") || n.includes("reno")) return "OPPO";
  if (n.includes("asus") || n.includes("rog")) return "ASUS";
  if (n.includes("vivo") || n.includes("iqoo")) return "vivo";
  return "Smartphone";
}

/**
 * Bảng mã màu Hex sắc nét và chính xác theo tên màu
 */
export function getSmartColorHex(colorName = "") {
  const n = (colorName || "").toLowerCase();
  if (n.includes("sa mạc") || n.includes("desert")) return "#c4b59d";
  if (n.includes("tự nhiên") || n.includes("natural")) return "#9a9790";
  if (n.includes("đen") || n.includes("black") || n.includes("midnight") || n.includes("tối")) return "#2b2b2d";
  if (n.includes("trắng") || n.includes("white") || n.includes("starlight") || n.includes("sứ") || n.includes("gốm")) return "#f8fafc";
  if (n.includes("xám") || n.includes("gray") || n.includes("grey") || n.includes("titan")) return "#71717a";
  if (n.includes("vàng") || n.includes("gold") || n.includes("yellow")) return "#eab308";
  if (n.includes("tím") || n.includes("violet") || n.includes("purple")) return "#7c3aed";
  if (n.includes("xanh dương") || n.includes("navy") || n.includes("blue") || n.includes("đại dương") || n.includes("biển") || n.includes("xanh")) return "#1d4ed8";
  if (n.includes("xanh lá") || n.includes("green") || n.includes("lục") || n.includes("ngọc")) return "#15803d";
  if (n.includes("hồng") || n.includes("pink") || n.includes("rose")) return "#f472b6";
  if (n.includes("bạc") || n.includes("silver")) return "#cbd5e1";
  if (n.includes("nâu") || n.includes("brown")) return "#78350f";
  return "#64748b";
}
